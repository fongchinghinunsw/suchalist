/**
 * Returns an HSL or HSLA color string
 * @param theme e.g. "blue"
 * @param shade e.g. 700
 * @param opacity optional opacity between 0 and 1
 */
export function getColor(theme: Theme, shade: Shade, opacity?: number): string {
  const hsl = palette[theme][shade];
  if (opacity != null) {
    return `hsla(${hsl}, ${opacity})`;
  }
  return `hsl(${hsl})`;
}
